    private const string WriteVariable = "CIVIC_LENS_WRITE_SCHEMA_DOCS";

    // Every table needs one owning feature, so a new table fails here until it is placed.
    private static readonly (string Feature, string[] Tables)[] TablesByFeature =
    [
        ("collection", ["collection_admission_batches", "collection_attempts", "collection_candidate_jobs", "collection_captures",
            "collection_collector_slot", "collection_configuration_revisions", "collection_discoveries", "collection_job_attempts",
            "collection_job_origins", "collection_jobs", "collection_source_schedules", "evidence_processing"]),
        ("bills", ["action_candidates", "bill_follow_on_jobs", "bill_gates", "bill_pages", "bill_stream_cursors", "bill_stream_pages"]),
        ("documents", ["document_comparisons", "document_extractions"]),
        ("analysis", ["document_change_analysis", "document_change_analysis_budget", "document_change_analysis_runs",
            "document_change_analysis_status"]),
        ("statements", ["statement_analysis", "statement_analysis_budget", "statement_analysis_runs", "statement_candidates",
            "statement_drafts", "statement_review_decisions", "statement_revisions"]),
        ("actions", ["action_analysis", "action_analysis_budget", "action_analysis_runs", "action_drafts", "action_review_decisions",
            "action_revisions"]),
        ("review", ["document_change_drafts", "document_change_review_decisions", "document_change_review_idempotency",
            "document_change_revisions"]),
        ("publication", ["publication_releases"])
    ];

    private string connectionString = null!;

    public async Task InitializeAsync() => connectionString = await postgres.CreateMigratedDatabaseAsync();

    public Task DisposeAsync() => postgres.DropDatabaseAsync(connectionString);

    [Fact]
    public async Task CheckedInSchemaReferenceMatchesTheMigratedDatabase()
    {
        var schema = await ReadSchemaAsync();
        var mapped = TablesByFeature.SelectMany(entry => entry.Tables).ToArray();
        Assert.Empty(schema.Keys.Except(mapped));
        Assert.Empty(mapped.Except(schema.Keys));
        Assert.Equal(mapped.Length, mapped.Distinct().Count());

        var directory = Path.Combine(RepositoryRoot.FullName, "docs", "architecture", "schema");
        var rendered = Render(schema);
        if (Environment.GetEnvironmentVariable(WriteVariable) == "1")
        {
            Directory.CreateDirectory(directory);
            foreach (var (feature, text) in rendered) await File.WriteAllTextAsync(Path.Combine(directory, feature + ".md"), text);
        }

        var stale = rendered.Where(entry => !File.Exists(Path.Combine(directory, entry.Key + ".md"))
                || File.ReadAllText(Path.Combine(directory, entry.Key + ".md")) != entry.Value)
            .Select(entry => entry.Key)
            .Concat(Directory.EnumerateFiles(directory, "*.md").Select(Path.GetFileNameWithoutExtension).Except(rendered.Keys)!)
            .ToArray();
        Assert.True(stale.Length == 0,
            $"docs/architecture/schema differs from the migrated database for: {string.Join(", ", stale)}. Run this test with {WriteVariable}=1 and commit the files.");
    }

    private static Dictionary<string, string> Render(IReadOnlyDictionary<string, TableSchema> schema)
    {
        var functionOwners = new Dictionary<string, string>();
        foreach (var (feature, trigger) in TablesByFeature.SelectMany(entry =>
                     entry.Tables.SelectMany(table => schema[table].Triggers).Select(trigger => (entry.Feature, trigger))))
            functionOwners.TryAdd(trigger.Function, feature);

        return TablesByFeature.ToDictionary(entry => entry.Feature, entry =>
        {
            var text = new StringBuilder()
                .Append("# ").Append(char.ToUpperInvariant(entry.Feature[0])).Append(entry.Feature[1..]).Append(" schema\n\n")
                .Append("Generated by `tests/CivicLens.Tests/Infrastructure/SchemaReferenceTests.cs` from the migrated database. Do not edit.\n");
            foreach (var table in entry.Tables.Order(StringComparer.Ordinal)) AppendTable(text, table, schema[table]);
            var functions = functionOwners.Where(owner => owner.Value == entry.Feature).Select(owner => owner.Key).Order(StringComparer.Ordinal).ToArray();
            if (functions.Length > 0)
            {
                text.Append("\n## Trigger functions\n\n");
                foreach (var function in functions)
                {
                    var users = schema.Values.SelectMany(table => table.Triggers).Where(trigger => trigger.Function == function)
                        .Select(trigger => trigger.Table).Distinct().Order(StringComparer.Ordinal);
                    text.Append("- ").Append(function).Append(": ").AppendJoin(", ", users).Append('\n');
                }
            }

            return text.ToString();
        });
    }

    private static void AppendTable(StringBuilder text, string name, TableSchema table)
    {
        text.Append("\n## ").Append(name).Append("\n\n");
        foreach (var line in table.Constraints.Where(line => line.StartsWith("pk ", StringComparison.Ordinal)))
            text.Append("- ").Append(line).Append('\n');
        foreach (var line in table.Constraints.Where(line => line.StartsWith("fk ", StringComparison.Ordinal)))
            text.Append("- ").Append(line).Append('\n');
        text.Append("- cols ").AppendJoin(", ", table.Columns).Append('\n');
        foreach (var line in table.Constraints.Where(line => !line.StartsWith("pk ", StringComparison.Ordinal) && !line.StartsWith("fk ", StringComparison.Ordinal)))
            text.Append("- ").Append(line).Append('\n');
        foreach (var line in table.Indexes) text.Append("- ").Append(line).Append('\n');
        foreach (var trigger in table.Triggers) text.Append("- ").Append(trigger.Line).Append('\n');
    }

    private async Task<IReadOnlyDictionary<string, TableSchema>> ReadSchemaAsync()
    {
        await using var connection = new NpgsqlConnection(connectionString);
        await connection.OpenAsync();
        var tables = new SortedDictionary<string, TableSchema>(StringComparer.Ordinal);
        TableSchema Table(string name) => tables.TryGetValue(name, out var table) ? table : tables[name] = new TableSchema();

        await foreach (var row in QueryAsync(connection, ColumnsSql))
            Table(row[0]).Columns.Add(ColumnLine(row[1], row[2], row[3] == "True", row[4], row[5]));
        await foreach (var row in QueryAsync(connection, ConstraintsSql))
            Table(row[0]).Constraints.Add(ConstraintLine(row[1], row[2], row[3]));
        await foreach (var row in QueryAsync(connection, IndexesSql))
            Table(row[0]).Indexes.Add(IndexLine(row[1].Replace("\"", "", StringComparison.Ordinal)));
        await foreach (var row in QueryAsync(connection, TriggersSql))
            Table(row[0]).Triggers.Add(new Trigger(row[0], TriggerLine(row[1]), row[2]));
        return tables;
    }

    private static string ColumnLine(string name, string type, bool notNull, string defaultValue, string generated)
    {
        var text = new StringBuilder(name).Append(' ').Append(Simplify(type
            .Replace("character varying", "varchar", StringComparison.Ordinal)
            .Replace("timestamp with time zone", "timestamptz", StringComparison.Ordinal)));
        if (!notNull) text.Append(" null");
        if (defaultValue.Length > 0) text.Append(generated == "s" ? " generated " : " default ").Append(Simplify(defaultValue));
        return text.ToString();
    }

    private static string ConstraintLine(string name, string type, string definition) => type switch
    {
        "p" => "pk " + definition["PRIMARY KEY ".Length..],
        "f" => ForeignKeyLine(definition),
        "u" => $"unique {name} {definition["UNIQUE ".Length..]}",
        "c" => $"check {name}: {Simplify(Unwrap(definition["CHECK ".Length..]))}",
        _ => $"constraint {name}: {Simplify(definition)}"
    };

    private static string ForeignKeyLine(string definition)
    {
        var match = Parsed(ForeignKeyPattern(), definition);
        var tail = match.Groups[4].Value.Trim().ToLowerInvariant();
        return $"fk {match.Groups[1].Value} -> {match.Groups[2].Value} {match.Groups[3].Value}{(tail.Length > 0 ? " " + tail : "")}";
    }

    private static string IndexLine(string definition)
    {
        var match = Parsed(IndexPattern(), definition);
        var text = new StringBuilder(match.Groups[1].Success ? "unique index " : "index ").Append(match.Groups[2].Value);
        if (match.Groups[3].Value != "btree") text.Append(" using ").Append(match.Groups[3].Value);
        text.Append(' ').Append(Simplify(match.Groups[4].Value));
        if (match.Groups[5].Success) text.Append(" where ").Append(Simplify(Unwrap(match.Groups[5].Value)));
        return text.ToString();
    }

    private static string TriggerLine(string definition)
    {
        var match = Parsed(TriggerPattern(), definition);
        var text = new StringBuilder("trigger ").Append(match.Groups[1].Value).Append(' ')
            .Append(match.Groups[2].Value.ToLowerInvariant()).Append(' ').Append(match.Groups[3].Value.ToLowerInvariant());
        if (match.Groups[4].Value == "STATEMENT") text.Append(" for each statement");
        if (match.Groups[5].Success) text.Append(" when ").Append(Simplify(match.Groups[5].Value));
        return text.Append(" -> ").Append(match.Groups[6].Value).ToString();
    }

    private static Match Parsed(Regex pattern, string definition)
    {
        var match = pattern.Match(definition);
        return match.Success ? match : throw new InvalidOperationException("The schema reference cannot render: " + definition);
    }

    private static string Unwrap(string expression) =>
        expression.StartsWith('(') && expression.EndsWith(')') ? expression[1..^1] : expression;

    private static string Simplify(string expression)
    {
        var text = CastPattern().Replace(expression, "");
        text = AnyArrayPattern().Replace(text, "in ($1)");
        return AllArrayPattern().Replace(text, "not in ($1)");
    }

    private static async IAsyncEnumerable<string[]> QueryAsync(NpgsqlConnection connection, string sql)
    {
        await using var command = new NpgsqlCommand(sql, connection);
        await using var reader = await command.ExecuteReaderAsync();
        while (await reader.ReadAsync())
            yield return Enumerable.Range(0, reader.FieldCount).Select(index => reader.IsDBNull(index) ? "" : Convert.ToString(reader.GetValue(index))!).ToArray();
    }

    private const string TablesFilter = """
        n.nspname = current_schema() AND c.relkind IN ('r', 'p') AND c.relname <> '__EFMigrationsHistory'
        """;

    private const string ColumnsSql = $"""
        SELECT c.relname, a.attname, format_type(a.atttypid, a.atttypmod), a.attnotnull, pg_get_expr(d.adbin, d.adrelid), a.attgenerated::text
          FROM pg_class c
          JOIN pg_namespace n ON n.oid = c.relnamespace
          JOIN pg_attribute a ON a.attrelid = c.oid AND a.attnum > 0 AND NOT a.attisdropped
          LEFT JOIN pg_attrdef d ON d.adrelid = c.oid AND d.adnum = a.attnum
         WHERE {TablesFilter}
         ORDER BY c.relname COLLATE "C", a.attnum
        """;

    private const string ConstraintsSql = $"""
        SELECT c.relname, k.conname, k.contype::text, pg_get_constraintdef(k.oid, true)
          FROM pg_constraint k
          JOIN pg_class c ON c.oid = k.conrelid
          JOIN pg_namespace n ON n.oid = c.relnamespace
         WHERE {TablesFilter} AND k.contype <> 'n'
         ORDER BY c.relname COLLATE "C", k.contype, k.conname COLLATE "C"
        """;

    private const string IndexesSql = $"""
        SELECT c.relname, pg_get_indexdef(x.indexrelid, 0, true)
          FROM pg_index x
          JOIN pg_class c ON c.oid = x.indrelid
          JOIN pg_class i ON i.oid = x.indexrelid
          JOIN pg_namespace n ON n.oid = c.relnamespace
         WHERE {TablesFilter}
           AND NOT EXISTS (SELECT 1 FROM pg_constraint k WHERE k.conrelid = x.indrelid AND k.conindid = x.indexrelid)
         ORDER BY c.relname COLLATE "C", i.relname COLLATE "C"
        """;

    private const string TriggersSql = $"""
        SELECT c.relname, pg_get_triggerdef(t.oid, true), p.proname
          FROM pg_trigger t
          JOIN pg_class c ON c.oid = t.tgrelid
          JOIN pg_namespace n ON n.oid = c.relnamespace
          JOIN pg_proc p ON p.oid = t.tgfoid
         WHERE {TablesFilter} AND NOT t.tgisinternal
         ORDER BY c.relname COLLATE "C", t.tgname COLLATE "C"
        """;

    [GeneratedRegex(@"^FOREIGN KEY (\(.*?\)) REFERENCES (\w+)(\(.*?\))(.*)$")]
    private static partial Regex ForeignKeyPattern();

    [GeneratedRegex(@"^CREATE (UNIQUE )?INDEX (\S+) ON \S+ USING (\w+) (.*?)(?: WHERE (.*))?$")]
    private static partial Regex IndexPattern();

    [GeneratedRegex(@"^CREATE TRIGGER (\w+) (BEFORE|AFTER|INSTEAD OF) (.*?) ON \S+ FOR EACH (ROW|STATEMENT) (?:WHEN \((.*)\) )?EXECUTE FUNCTION (\w+)\(.*\)$")]
    private static partial Regex TriggerPattern();

    [GeneratedRegex(@"::(?:text|character varying|bigint|integer|smallint|boolean|jsonb|bytea|numeric|timestamp with time zone|regclass)(?:\[\])?")]
    private static partial Regex CastPattern();

    [GeneratedRegex(@"= ANY \(ARRAY\[(.*?)\]\)")]
    private static partial Regex AnyArrayPattern();

    [GeneratedRegex(@"<> ALL \(ARRAY\[(.*?)\]\)")]
    private static partial Regex AllArrayPattern();

    private sealed class TableSchema
    {
        public List<string> Columns { get; } = [];
        public List<string> Constraints { get; } = [];
        public List<string> Indexes { get; } = [];
        public List<Trigger> Triggers { get; } = [];
    }

    private sealed record Trigger(string Table, string Line, string Function);
}
